/// Evaluator for rubric-based assessment of a multi-turn agent trajectory.
class RubricBasedMultiTurnTrajectoryEvaluator extends RubricBasedEvaluator {
  /// Creates a rubric-based multi-turn trajectory evaluator.
  RubricBasedMultiTurnTrajectoryEvaluator(
    EvalMetricSpec evalMetric, {
    super.autoRaterInvoker,
  }) : super(evalMetric: evalMetric, rubricType: 'TRAJECTORY_QUALITY');

  String _formattedDialogue = '';
  String _formattedInstructions = '';
  String _formattedTools = '';

  @override
  Future<EvaluationResult> evaluateInvocations({
    required List<Invocation> actualInvocations,
    List<Invocation>? expectedInvocations,
    ConversationScenario? conversationScenario,
  }) async {
    if (actualInvocations.isEmpty) {
      return EvaluationResult();
    }

    _assembleDialogueHistory(actualInvocations);

    final List<Invocation?> expected = expectedInvocations == null
        ? List<Invocation?>.filled(actualInvocations.length, null)
        : expectedInvocations.cast<Invocation?>();

    Invocation? expectedAt(int index) {
      if (index < 0 || index >= expected.length) {
        return null;
      }
      return expected[index];
    }

    final int lastIndex = actualInvocations.length - 1;
    final List<PerInvocationResult> perInvocationResults =
        <PerInvocationResult>[];
    for (int i = 0; i < lastIndex; i += 1) {
      perInvocationResults.add(
        PerInvocationResult(
          actualInvocation: actualInvocations[i],
          expectedInvocation: expectedAt(i),
          evalStatus: EvalStatus.notEvaluated,
        ),
      );
    }

    final Invocation? lastExpected = expectedAt(lastIndex);
    final EvaluationResult lastTurnResult = await super.evaluateInvocations(
      actualInvocations: <Invocation>[actualInvocations[lastIndex]],
      expectedInvocations: lastExpected == null
          ? null
          : <Invocation>[lastExpected],
      conversationScenario: conversationScenario,
    );

    if (lastTurnResult.perInvocationResults.isNotEmpty) {
      perInvocationResults.addAll(lastTurnResult.perInvocationResults);
    } else {
      perInvocationResults.add(
        PerInvocationResult(
          actualInvocation: actualInvocations[lastIndex],
          expectedInvocation: lastExpected,
          score: lastTurnResult.overallScore,
          evalStatus: lastTurnResult.overallEvalStatus,
          rubricScores: lastTurnResult.overallRubricScores,
        ),
      );
    }

    return EvaluationResult(
      overallScore: lastTurnResult.overallScore,
      overallEvalStatus: lastTurnResult.overallEvalStatus,
      perInvocationResults: perInvocationResults,
      overallRubricScores: lastTurnResult.overallRubricScores,
    );
  }

  @override
  String formatAutoRaterPrompt(
    Invocation actualInvocation,
    Invocation? expectedInvocation,
  ) {
    createEffectiveRubricsList(actualInvocation.rubrics);

    final List<Map<String, Object?>> rubrics = getEffectiveRubricsList()
        .map((Rubric rubric) {
          return <String, Object?>{
            'property': rubric.rubricContent.textProperty ?? '',
            if (rubric.type != null) 'type': rubric.type,
          };
        })
        .toList(growable: false);

    return _rubricBasedMultiTurnTrajectoryQualityV1Prompt
        .replaceAll('{agent_instructions}', _formattedInstructions)
        .replaceAll('{agent_tool_definitions}', _formattedTools)
        .replaceAll('{user_agent_dialogue}', _formattedDialogue)
        .replaceAll(
          '{properties}',
          const JsonEncoder.withIndent('  ').convert(rubrics),
        );
  }

  void _assembleDialogueHistory(List<Invocation> actualInvocations) {
    final List<String> dialogueLines = <String>[];
    for (int turnIndex = 0; turnIndex < actualInvocations.length; turnIndex++) {
      final Invocation invocation = actualInvocations[turnIndex];
      final int turnNumber = turnIndex + 1;

      final String? userText = _textFromContent(invocation.userContent);
      if (userText != null && userText.isNotEmpty) {
        dialogueLines.add('USER TURN $turnNumber: $userText');
      }

      final Object? intermediate = invocation.intermediateData;
      if (intermediate is InvocationEvents) {
        for (final InvocationEvent event in intermediate.invocationEvents) {
          final String role = event.author.toLowerCase() == 'user'
              ? 'USER'
              : 'AGENT (${event.author})';
          final EvalJsonMap? content = event.content;
          if (content == null) {
            continue;
          }
          final String? text = _textFromContent(content);
          if (text != null && text.isNotEmpty) {
            dialogueLines.add('$role TURN $turnNumber: $text');
          }
          for (final EvalJsonMap call in _functionCallsFromContent(content)) {
            final String name = _nameFromPayload(call);
            final Object args = call['args'] ?? <String, Object?>{};
            dialogueLines.add(
              '$role TURN $turnNumber (tool call): $name(${jsonEncode(args)})',
            );
          }
          for (final EvalJsonMap response in _functionResponsesFromContent(
            content,
          )) {
            final String name = _nameFromPayload(response);
            final Object payload = response['response'] ?? <String, Object?>{};
            dialogueLines.add(
              '$role TURN $turnNumber (tool output): $name -> ${jsonEncode(payload)}',
            );
          }
        }
      }

      final EvalJsonMap? finalResponse = invocation.finalResponse;
      final String? agentText = _textFromContent(finalResponse);
      if (agentText != null && agentText.isNotEmpty) {
        final String agentName = _firstEventAuthor(intermediate) ?? 'agent';
        dialogueLines.add('AGENT ($agentName) TURN $turnNumber: $agentText');
      }
    }
    _formattedDialogue = dialogueLines.join('\n');

    final List<String> instructionParts = <String>[];
    final List<String> toolParts = <String>[];
    for (final Invocation invocation in actualInvocations) {
      final AppDetails? appDetails = invocation.appDetails;
      if (appDetails == null) {
        continue;
      }
      appDetails.agentDetails.forEach((String agentId, AgentDetails details) {
        instructionParts.add(
          'Agent $agentId Instructions:\n${details.instructions}',
        );
        toolParts.add('Agent: $agentId');
        for (final Object? declaration in details.toolDeclarations) {
          for (final (String name, String description) in _functionDeclarations(
            declaration,
          )) {
            toolParts.add('- $name: $description');
          }
        }
      });
    }
    _formattedInstructions = _dedupe(instructionParts).join('\n\n');
    _formattedTools = _dedupe(toolParts).join('\n');
  }
}

String? _textFromContent(EvalJsonMap? content) {
  if (content == null) {
    return null;
  }
  final List<String> parts = asObjectList(content['parts'])
      .map((Object? part) => asNullableString(asEvalJson(part)['text']) ?? '')
      .where((String text) => text.isNotEmpty)
      .toList(growable: false);
  return parts.isEmpty ? null : parts.join(' ');
}

List<EvalJsonMap> _functionCallsFromContent(EvalJsonMap content) {
  final List<EvalJsonMap> result = <EvalJsonMap>[];
  for (final Object? part in asObjectList(content['parts'])) {
    final EvalJsonMap partMap = asEvalJson(part);
    final Object? raw = partMap['function_call'] ?? partMap['functionCall'];
    if (raw != null) {
      final EvalJsonMap call = asEvalJson(raw);
      if (call.isNotEmpty) {
        result.add(call);
      }
    }
  }
  return result;
}

List<EvalJsonMap> _functionResponsesFromContent(EvalJsonMap content) {
  final List<EvalJsonMap> result = <EvalJsonMap>[];
  for (final Object? part in asObjectList(content['parts'])) {
    final EvalJsonMap partMap = asEvalJson(part);
    final Object? raw =
        partMap['function_response'] ?? partMap['functionResponse'];
    if (raw != null) {
      final EvalJsonMap response = asEvalJson(raw);
      if (response.isNotEmpty) {
        result.add(response);
      }
    }
  }
  return result;
}

String _nameFromPayload(EvalJsonMap payload) {
  return asNullableString(payload['name']) ?? '';
}

String? _firstEventAuthor(Object? intermediateData) {
  if (intermediateData is InvocationEvents &&
      intermediateData.invocationEvents.isNotEmpty) {
    final String author = intermediateData.invocationEvents.first.author;
    return author.isEmpty ? null : author;
  }
  return null;
}

Iterable<(String, String)> _functionDeclarations(Object? declaration) sync* {
  if (declaration is ToolDeclaration) {
    for (final FunctionDeclaration function
        in declaration.functionDeclarations) {
      yield (function.name, function.description);
    }
    return;
  }
  if (declaration is FunctionDeclaration) {
    yield (declaration.name, declaration.description);
    return;
  }
  final EvalJsonMap map = asEvalJson(declaration);
  if (map.isEmpty) {
    return;
  }
  final Object? rawFunctions =
      map['function_declarations'] ?? map['functionDeclarations'];
  if (rawFunctions != null) {
    for (final Object? rawFunction in asObjectList(rawFunctions)) {
      final EvalJsonMap function = asEvalJson(rawFunction);
      final String name = asNullableString(function['name']) ?? '';
      if (name.isEmpty) {
        continue;
      }
      yield (name, asNullableString(function['description']) ?? '');
    }
    return;
  }
  final String name = asNullableString(map['name']) ?? '';
  if (name.isNotEmpty) {
    yield (name, asNullableString(map['description']) ?? '');
  }
}

List<String> _dedupe(List<String> values) {
  final Set<String> seen = <String>{};
  final List<String> result = <String>[];
  for (final String value in values) {
    if (seen.add(value)) {
      result.add(value);
    }
  }
  return result;
}
