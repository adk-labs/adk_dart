import 'package:flutter/material.dart';

import '../theme/adk_theme.dart';

/// A collapsible card widget displayed in the chat timeline when earlier conversation history is compacted (`EventActions.compaction`).
class AdkCompactionSummaryCard extends StatefulWidget {
  /// Creates an [AdkCompactionSummaryCard].
  const AdkCompactionSummaryCard({
    super.key,
    required this.summaryText,
    this.title = 'Conversation History Compacted',
    this.initiallyExpanded = false,
    this.style,
    this.leadingIcon,
    this.trailingWidget,
    this.headerBuilder,
    this.summaryBuilder,
  });

  /// Compacted summary text generated by the sliding-window or token-threshold compactor.
  final String summaryText;

  /// Header label displayed on the compaction banner.
  final String title;

  /// Whether the full summary text is expanded by default.
  final bool initiallyExpanded;

  /// Optional style configuration overriding theme defaults.
  final AdkCardStyle? style;

  /// Optional custom leading icon widget in the header.
  final Widget? leadingIcon;

  /// Optional custom trailing widget in the header.
  final Widget? trailingWidget;

  /// Optional custom builder to replace the header row.
  final Widget Function(
    BuildContext context,
    String title,
    bool isExpanded,
    VoidCallback onToggle,
  )? headerBuilder;

  /// Optional custom builder to replace the expanded summary body.
  final Widget Function(BuildContext context, String cleanedSummary)?
      summaryBuilder;

  @override
  State<AdkCompactionSummaryCard> createState() =>
      _AdkCompactionSummaryCardState();
}

class _AdkCompactionSummaryCardState extends State<AdkCompactionSummaryCard> {
  late bool _isExpanded;

  @override
  void initState() {
    super.initState();
    _isExpanded = widget.initiallyExpanded;
  }

  void _toggle() => setState(() => _isExpanded = !_isExpanded);

  String get _cleanedSummary {
    final String trimmed = widget.summaryText.trim();
    if (trimmed.startsWith('Session compacted:')) {
      return trimmed.substring('Session compacted:'.length).trim();
    }
    return trimmed;
  }

  @override
  Widget build(BuildContext context) {
    final ThemeData theme = Theme.of(context);
    final AdkCardStyle? effectiveStyle =
        AdkTheme.of(context).compactionCardStyle?.merge(widget.style) ??
        widget.style;
    final String summary = _cleanedSummary;
    final BorderRadius radius =
        effectiveStyle?.borderRadius ?? BorderRadius.circular(10.0);

    return Container(
      margin: effectiveStyle?.margin ??
          const EdgeInsets.symmetric(vertical: 6.0, horizontal: 16.0),
      decoration: effectiveStyle?.decoration ??
          BoxDecoration(
            color: effectiveStyle?.backgroundColor ??
                theme.colorScheme.secondaryContainer.withValues(alpha: 0.45),
            borderRadius: radius,
            border: Border.all(
              color: effectiveStyle?.borderColor ??
                  theme.colorScheme.secondary.withValues(alpha: 0.3),
            ),
          ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        mainAxisSize: MainAxisSize.min,
        children: <Widget>[
          if (widget.headerBuilder != null)
            widget.headerBuilder!(context, widget.title, _isExpanded, _toggle)
          else
            InkWell(
              onTap: _toggle,
              borderRadius: radius,
              child: Container(
                color: effectiveStyle?.headerBackgroundColor,
                padding: effectiveStyle?.padding ??
                    const EdgeInsets.symmetric(
                      horizontal: 12.0,
                      vertical: 8.0,
                    ),
                child: Row(
                  children: <Widget>[
                    widget.leadingIcon ??
                        Icon(
                          Icons.compress_rounded,
                          size: 16.0,
                          color: effectiveStyle?.accentColor ??
                              theme.colorScheme.secondary,
                        ),
                    const SizedBox(width: 8.0),
                    Expanded(
                      child: Text(
                        widget.title,
                        style: effectiveStyle?.titleStyle ??
                            theme.textTheme.labelMedium?.copyWith(
                              fontWeight: FontWeight.w700,
                              color: effectiveStyle?.textColor ??
                                  theme.colorScheme.onSecondaryContainer,
                            ),
                      ),
                    ),
                    if (widget.trailingWidget != null) ...<Widget>[
                      widget.trailingWidget!,
                      const SizedBox(width: 6.0),
                    ],
                    Icon(
                      _isExpanded ? Icons.expand_less : Icons.expand_more,
                      size: 18.0,
                      color: effectiveStyle?.textColor ??
                          theme.colorScheme.onSecondaryContainer,
                    ),
                  ],
                ),
              ),
            ),
          if (_isExpanded && summary.isNotEmpty) ...<Widget>[
            Divider(
              height: 1.0,
              color: theme.colorScheme.secondary.withValues(alpha: 0.2),
            ),
            Padding(
              padding: effectiveStyle?.padding ?? const EdgeInsets.all(12.0),
              child: widget.summaryBuilder != null
                  ? widget.summaryBuilder!(context, summary)
                  : SelectableText(
                      summary,
                      style: effectiveStyle?.bodyStyle ??
                          theme.textTheme.bodySmall?.copyWith(
                            color: effectiveStyle?.textColor ??
                                theme.colorScheme.onSecondaryContainer,
                          ),
                    ),
            ),
          ],
        ],
      ),
    );
  }
}
